// Builds the downloadable / uploadable zips.
//
//   npm run package                                   full web package (server, docs, all skins)
//   npm run package -- --target youtube               YouTube Playables upload
//   npm run package -- --target crazygames            CrazyGames upload
//   npm run package -- --target gamedistribution --gd-id <your game id>
//   add  --skin <id>  to bake a different skin into a platform build
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

const args = process.argv.slice(2);
const opt = (name, def) => { const i = args.indexOf(`--${name}`); return i >= 0 ? args[i + 1] : def; };
const TARGETS = ['web', 'youtube', 'crazygames', 'gamedistribution'];
const target = opt('target', 'web');
if (!TARGETS.includes(target)) fail(`Unknown --target "${target}". Use one of: ${TARGETS.join(', ')}`);
const configSrc = fs.readFileSync(path.join(ROOT, 'js/config.js'), 'utf8');
const defaultSkin = configSrc.match(/DEFAULT_VENDOR = '([^']+)'/)[1];
const skin = opt('skin', defaultSkin);
if (!fs.existsSync(path.join(ROOT, 'vendors', skin, 'vendor.json'))) fail(`No skin vendors/${skin}/vendor.json`);
const gdId = opt('gd-id', '');
if (target === 'gamedistribution' && !gdId) console.warn('Warning: no --gd-id given; set gameDistributionId in js/platform-config.js before uploading.');

// SDK <script> tags that must load before the game (YouTube requires its SDK to be the first script).
const SDK_TAGS = {
  youtube: '<script src="https://www.youtube.com/game_api/v1"></script>',
  crazygames: '<script src="https://sdk.crazygames.com/crazygames-sdk-v3.js"></script>',
};
const ALLOWED_URLS = ['https://www.youtube.com/game_api/v1', 'https://sdk.crazygames.com/crazygames-sdk-v3.js', 'https://html5.api.gamedistribution.com/main.min.js'];

const isWeb = target === 'web';
const NAME = isWeb ? `${pkg.name}-v${pkg.version}` : `${pkg.name}-${target}${skin !== defaultSkin ? `-${skin}` : ''}-v${pkg.version}`;
const DIST = path.join(ROOT, 'dist');
const STAGE = path.join(DIST, NAME);

// Web: everything a buyer needs. Platform builds: only the static game, one skin.
const INCLUDE = isWeb
  ? ['index.html', 'css', 'js', 'vendor', 'vendors', 'assets', 'documentation', 'tools', 'server.js', 'ecosystem.config.cjs', 'package.json', 'README.md', 'LICENSE.txt']
  : ['index.html', 'css', 'js', 'vendor', `vendors/${skin}`, 'assets'];
const SKIP = new Set(['.DS_Store', 'Thumbs.db', 'marketing']); // marketing images are for store listings, not the download

function fail(msg) { console.error(msg); process.exit(1); }

function copy(src, dst) {
  if (fs.statSync(src).isDirectory()) {
    fs.mkdirSync(dst, { recursive: true });
    for (const f of fs.readdirSync(src)) if (!SKIP.has(f)) copy(path.join(src, f), path.join(dst, f));
  } else {
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    fs.copyFileSync(src, dst);
  }
}

fs.rmSync(STAGE, { recursive: true, force: true });
fs.mkdirSync(STAGE, { recursive: true });
for (const item of INCLUDE) {
  const src = path.join(ROOT, item);
  if (!fs.existsSync(src)) fail(`Missing ${item}`);
  copy(src, path.join(STAGE, item));
}

if (!isWeb) {
  // bake the platform + skin into the build
  fs.writeFileSync(path.join(STAGE, 'js/platform-config.js'),
    `// Generated by tools/package.js for the ${target} build.\nexport const PLATFORM_CONFIG = ${JSON.stringify({ target, vendor: skin, gameDistributionId: gdId })};\n`);
  if (SDK_TAGS[target]) {
    const file = path.join(STAGE, 'index.html');
    const html = fs.readFileSync(file, 'utf8').replace('<meta charset="utf-8">', `<meta charset="utf-8">\n  ${SDK_TAGS[target]}`);
    fs.writeFileSync(file, html);
  }
  fs.copyFileSync(path.join(ROOT, 'LICENSE.txt'), path.join(STAGE, 'CREDITS-AND-LICENSE.txt'));
}

// No network requests besides the platform SDK: scan our own code for absolute URLs.
const leaks = [];
for (const dir of ['index.html', 'css', 'js']) {
  const walk = (p) => {
    if (fs.statSync(p).isDirectory()) return fs.readdirSync(p).forEach((f) => walk(path.join(p, f)));
    if (!/\.(html|css|js)$/.test(p)) return;
    const text = fs.readFileSync(p, 'utf8');
    for (const m of text.matchAll(/https?:\/\/[^\s'"`)<>]+/g)) {
      const line = text.slice(text.lastIndexOf('\n', m.index) + 1, text.indexOf('\n', m.index));
      if (ALLOWED_URLS.includes(m[0]) || /^\s*(\/\/|\*)/.test(line)) continue; // SDKs or comments
      if (m[0].startsWith('http://localhost')) continue;
      leaks.push(`${path.relative(STAGE, p)}: ${m[0]}`);
    }
  };
  walk(path.join(STAGE, dir));
}
if (leaks.length) fail(`External URLs found in the build:\n  ${leaks.join('\n  ')}`);

const zip = path.join(DIST, `${NAME}.zip`);
fs.rmSync(zip, { force: true });
try {
  // platform uploads want index.html at the zip root; the web package keeps a top folder
  if (isWeb) execFileSync('zip', ['-rq9', zip, NAME], { cwd: DIST });
  else execFileSync('zip', ['-rq9', zip, '.'], { cwd: STAGE });
} catch {
  fail(`Could not run the "zip" command. The files are ready in ${STAGE} — zip that folder manually.`);
}
console.log(`Created ${path.relative(ROOT, zip)} (${(fs.statSync(zip).size / 1048576).toFixed(1)} MB) — target: ${target}, skin: ${isWeb ? 'all' : skin}`);
